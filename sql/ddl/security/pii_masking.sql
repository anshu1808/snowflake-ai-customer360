-- OPTIONAL (needs Enterprise edition or higher): column-level PII masking.
-- Run with: python -m src.pipeline.run security
-- Roles that may see raw PII: {{PII_ROLE}} and the pipeline/deploy role {{ROLE}}.
-- ACCOUNTADMIN is intentionally NOT exempt.

CREATE MASKING POLICY IF NOT EXISTS SILVER.PII_STRING_MASK AS (VAL VARCHAR) RETURNS VARCHAR ->
    CASE 
        WHEN IS_ROLE_IN_SESSION('{{PII_ROLE}}') OR CURRENT_ROLE()='{{ROLE}}' THEN VAL
        WHEN VAL IS NULL THEN NULL
        ELSE '***MASKED***'
    END;

    CREATE MASKING POLICY IF NOT EXISTS SILVER.PII_DATE_MASK AS (VAL DATE) RETURNS DATE->
    CASE
        WHEN IS_ROLE_IN_SESSION('{{PII_ROLE}}') OR CURRENT_ROLE()='{{ROLE}}' THEN VAL
        ELSE NULL
    END;

    ALTER TABLE SILVER.CUSTOMER MODIFY COLUMN EMAIL SET MASKING POLICY SILVER.PII_STRING_MASK;
    ALTER TABLE SILVER.CUSTOMER MODIFY COLUMN PHONE SET MASKING POLICY SILVER.PII_STRING_MASK;
    ALTER TABLE SILVER.CUSTOMER MODIFY COLUMN DATE_OF_BIRTH SET MASKING POLICY SILVER.PII_DATE_MASK;
    ALTER TABLE GOLD.CUSTOMER_360 MODIFY COLUMN EMAIL SET MASKING POLICY SILVER.PII_STRING_MASK;
    ALTER TABLE GOLD.CUSTOMER_360 MODIFY COLUMN PHONE SET MASKING POLICY SILVER.PII_STRING_MASK;