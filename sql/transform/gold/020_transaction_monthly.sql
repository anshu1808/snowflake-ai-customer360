INSERT OVERWRITE INTO GOLD.TRANSACTION_MONTHLY (
    CUSTOMER_ID, MONTH_START, TXN_COUNT, DEBIT_AMOUNT, CREDIT_AMOUNT, NET_AMOUNT, DISTINCT_MERCHANTS
)
SELECT
    CUSTOMER_ID,
    DATE_TRUNC('month', TRANSACTION_TIMESTAMP)::DATE                AS MONTH_START,
    COUNT(*)                                                        AS TXN_COUNT,
    SUM(IFF(TRANSACTION_TYPE = 'DEBIT',  AMOUNT, 0))                AS DEBIT_AMOUNT,
    SUM(IFF(TRANSACTION_TYPE = 'CREDIT', AMOUNT, 0))                AS CREDIT_AMOUNT,
    SUM(IFF(TRANSACTION_TYPE = 'CREDIT', AMOUNT, 0))
      - SUM(IFF(TRANSACTION_TYPE = 'DEBIT', AMOUNT, 0))             AS NET_AMOUNT,
    COUNT(DISTINCT MERCHANT)                                        AS DISTINCT_MERCHANTS
FROM SILVER.TRANSACTION
WHERE TRANSACTION_STATUS = 'COMPLETED'
GROUP BY CUSTOMER_ID, DATE_TRUNC('month', TRANSACTION_TIMESTAMP)::DATE;
