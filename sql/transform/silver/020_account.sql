MERGE INTO SILVER.ACCOUNT AS t
USING (
    SELECT
        UPPER(TRIM(ACCOUNT_ID))        AS ACCOUNT_ID,
        UPPER(TRIM(CUSTOMER_ID))       AS CUSTOMER_ID,
        UPPER(TRIM(ACCOUNT_TYPE))      AS ACCOUNT_TYPE,
        UPPER(TRIM(ACCOUNT_STATUS))    AS ACCOUNT_STATUS,
        OPENING_DATE,
        BALANCE,
        UPPER(TRIM(CURRENCY))          AS CURRENCY,
        UPDATED_AT,
        INGESTED_AT
    FROM BRONZE.ACCOUNT_RAW
    WHERE NULLIF(TRIM(ACCOUNT_ID), '') IS NOT NULL
      AND NULLIF(TRIM(CUSTOMER_ID), '') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY UPPER(TRIM(ACCOUNT_ID))
        ORDER BY UPDATED_AT DESC NULLS LAST, INGESTED_AT DESC NULLS LAST
    ) = 1
) AS s
ON t.ACCOUNT_ID = s.ACCOUNT_ID
WHEN MATCHED AND (t.UPDATED_AT IS NULL OR s.UPDATED_AT > t.UPDATED_AT) THEN UPDATE SET
    CUSTOMER_ID    = s.CUSTOMER_ID,
    ACCOUNT_TYPE   = s.ACCOUNT_TYPE,
    ACCOUNT_STATUS = s.ACCOUNT_STATUS,
    OPENING_DATE   = s.OPENING_DATE,
    BALANCE        = s.BALANCE,
    CURRENCY       = s.CURRENCY,
    UPDATED_AT     = s.UPDATED_AT,
    INGESTED_AT    = s.INGESTED_AT
WHEN NOT MATCHED THEN INSERT (
    ACCOUNT_ID, CUSTOMER_ID, ACCOUNT_TYPE, ACCOUNT_STATUS, OPENING_DATE,
    BALANCE, CURRENCY, UPDATED_AT, INGESTED_AT
) VALUES (
    s.ACCOUNT_ID, s.CUSTOMER_ID, s.ACCOUNT_TYPE, s.ACCOUNT_STATUS, s.OPENING_DATE,
    s.BALANCE, s.CURRENCY, s.UPDATED_AT, s.INGESTED_AT
);
