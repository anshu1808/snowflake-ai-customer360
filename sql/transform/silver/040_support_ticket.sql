MERGE INTO SILVER.SUPPORT_TICKET AS t
USING (
    SELECT
        UPPER(TRIM(TICKET_ID))     AS TICKET_ID,
        UPPER(TRIM(CUSTOMER_ID))   AS CUSTOMER_ID,
        CREATED_AT,
        UPPER(TRIM(CATEGORY))      AS CATEGORY,
        UPPER(TRIM(PRIORITY))      AS PRIORITY,
        UPPER(TRIM(STATUS))        AS STATUS,
        TRIM(SUBJECT)              AS SUBJECT,
        TRIM(DESCRIPTION)          AS DESCRIPTION,
        INGESTED_AT
    FROM BRONZE.SUPPORT_TICKET_RAW
    WHERE NULLIF(TRIM(TICKET_ID), '') IS NOT NULL
      AND NULLIF(TRIM(CUSTOMER_ID), '') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY UPPER(TRIM(TICKET_ID))
        ORDER BY INGESTED_AT DESC NULLS LAST, CREATED_AT DESC NULLS LAST
    ) = 1
) AS s
ON t.TICKET_ID = s.TICKET_ID
WHEN MATCHED AND (t.INGESTED_AT IS NULL OR s.INGESTED_AT > t.INGESTED_AT) THEN UPDATE SET
    CUSTOMER_ID = s.CUSTOMER_ID,
    CREATED_AT  = s.CREATED_AT,
    CATEGORY    = s.CATEGORY,
    PRIORITY    = s.PRIORITY,
    STATUS      = s.STATUS,
    SUBJECT     = s.SUBJECT,
    DESCRIPTION = s.DESCRIPTION,
    INGESTED_AT = s.INGESTED_AT
WHEN NOT MATCHED THEN INSERT (
    TICKET_ID, CUSTOMER_ID, CREATED_AT, CATEGORY, PRIORITY, STATUS, SUBJECT, DESCRIPTION, INGESTED_AT
) VALUES (
    s.TICKET_ID, s.CUSTOMER_ID, s.CREATED_AT, s.CATEGORY, s.PRIORITY, s.STATUS, s.SUBJECT, s.DESCRIPTION, s.INGESTED_AT
);
