MERGE INTO SILVER.PRODUCT AS t
USING (
    SELECT
        UPPER(TRIM(PRODUCT_ID))        AS PRODUCT_ID,
        TRIM(PRODUCT_NAME)             AS PRODUCT_NAME,
        UPPER(TRIM(PRODUCT_TYPE))      AS PRODUCT_TYPE,
        UPPER(TRIM(PRODUCT_CATEGORY))  AS PRODUCT_CATEGORY,
        ANNUAL_FEE,
        INTEREST_RATE,
        UPPER(TRIM(STATUS))            AS STATUS,
        INGESTED_AT
    FROM BRONZE.PRODUCT_RAW
    WHERE NULLIF(TRIM(PRODUCT_ID), '') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY UPPER(TRIM(PRODUCT_ID))
        ORDER BY INGESTED_AT DESC NULLS LAST
    ) = 1
) AS s
ON t.PRODUCT_ID = s.PRODUCT_ID
WHEN MATCHED AND (t.INGESTED_AT IS NULL OR s.INGESTED_AT > t.INGESTED_AT) THEN UPDATE SET
    PRODUCT_NAME     = s.PRODUCT_NAME,
    PRODUCT_TYPE     = s.PRODUCT_TYPE,
    PRODUCT_CATEGORY = s.PRODUCT_CATEGORY,
    ANNUAL_FEE       = s.ANNUAL_FEE,
    INTEREST_RATE    = s.INTEREST_RATE,
    STATUS           = s.STATUS,
    INGESTED_AT      = s.INGESTED_AT
WHEN NOT MATCHED THEN INSERT (
    PRODUCT_ID, PRODUCT_NAME, PRODUCT_TYPE, PRODUCT_CATEGORY, ANNUAL_FEE, INTEREST_RATE, STATUS, INGESTED_AT
) VALUES (
    s.PRODUCT_ID, s.PRODUCT_NAME, s.PRODUCT_TYPE, s.PRODUCT_CATEGORY, s.ANNUAL_FEE, s.INTEREST_RATE, s.STATUS, s.INGESTED_AT
);
