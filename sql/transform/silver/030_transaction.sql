-- Transactions have no UPDATED_AT: the most recently ingested version wins
-- (e.g. a PENDING row later re-delivered as COMPLETED).

MERGE INTO SILVER.TRANSACTION AS t
USING (
    SELECT
        UPPER(TRIM(TRANSACTION_ID))     AS TRANSACTION_ID,
        UPPER(TRIM(ACCOUNT_ID))         AS ACCOUNT_ID,
        UPPER(TRIM(CUSTOMER_ID))        AS CUSTOMER_ID,
        TRANSACTION_TIMESTAMP,
        UPPER(TRIM(TRANSACTION_TYPE))   AS TRANSACTION_TYPE,
        AMOUNT,
        UPPER(TRIM(CURRENCY))           AS CURRENCY,
        TRIM(MERCHANT)                  AS MERCHANT,
        UPPER(TRIM(TRANSACTION_STATUS)) AS TRANSACTION_STATUS,
        INGESTED_AT
    FROM BRONZE.TRANSACTION_RAW
    WHERE NULLIF(TRIM(TRANSACTION_ID), '') IS NOT NULL
      AND NULLIF(TRIM(ACCOUNT_ID), '') IS NOT NULL
      AND NULLIF(TRIM(CUSTOMER_ID), '') IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY UPPER(TRIM(TRANSACTION_ID))
        ORDER BY INGESTED_AT DESC NULLS LAST, TRANSACTION_TIMESTAMP DESC NULLS LAST
    ) = 1
) AS s
ON t.TRANSACTION_ID = s.TRANSACTION_ID
WHEN MATCHED AND (t.INGESTED_AT IS NULL OR s.INGESTED_AT > t.INGESTED_AT) THEN UPDATE SET
    ACCOUNT_ID            = s.ACCOUNT_ID,
    CUSTOMER_ID           = s.CUSTOMER_ID,
    TRANSACTION_TIMESTAMP = s.TRANSACTION_TIMESTAMP,
    TRANSACTION_TYPE      = s.TRANSACTION_TYPE,
    AMOUNT                = s.AMOUNT,
    CURRENCY              = s.CURRENCY,
    MERCHANT              = s.MERCHANT,
    TRANSACTION_STATUS    = s.TRANSACTION_STATUS,
    INGESTED_AT           = s.INGESTED_AT
WHEN NOT MATCHED THEN INSERT (
    TRANSACTION_ID, ACCOUNT_ID, CUSTOMER_ID, TRANSACTION_TIMESTAMP, TRANSACTION_TYPE,
    AMOUNT, CURRENCY, MERCHANT, TRANSACTION_STATUS, INGESTED_AT
) VALUES (
    s.TRANSACTION_ID, s.ACCOUNT_ID, s.CUSTOMER_ID, s.TRANSACTION_TIMESTAMP, s.TRANSACTION_TYPE,
    s.AMOUNT, s.CURRENCY, s.MERCHANT, s.TRANSACTION_STATUS, s.INGESTED_AT
);
