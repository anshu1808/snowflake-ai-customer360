-- OPTIONAL (Cortex): requires the SNOWFLAKE.CORTEX_USER database role and a region where
-- Cortex LLM functions are available. Run with: python -m src.pipeline.run ai

CREATE TABLE IF NOT EXISTS GOLD.SUPPORT_TICKET_ENRICHED (
    TICKET_ID VARCHAR NOT NULL,
    CUSTOMER_ID VARCHAR,
    CREATED_AT TIMESTAMP_NTZ,
    CATEGORY VARCHAR,
    PRIORITY VARCHAR,
    STATUS VARCHAR,
    SUBJECT VARCHAR,
    DESCRIPTION VARCHAR,
    SENTIMENT_SCORE FLOAT,
    SENTIMENT_LABEL VARCHAR,
    REFRESHED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Only score tickets that are new (cheap + idempotent): Cortex is billed per call.
INSERT INTO GOLD.SUPPORT_TICKET_ENRICHED (
    TICKET_ID, CUSTOMER_ID, CREATED_AT, CATEGORY, PRIORITY, STATUS, SUBJECT, DESCRIPTION,
    SENTIMENT_SCORE, SENTIMENT_LABEL
)
SELECT
    n.TICKET_ID, n.CUSTOMER_ID, n.CREATED_AT, n.CATEGORY, n.PRIORITY, n.STATUS, n.SUBJECT, n.DESCRIPTION,
    n.SCORE,
    CASE WHEN n.SCORE <= -0.25 THEN 'NEGATIVE' WHEN n.SCORE >= 0.25 THEN 'POSITIVE' ELSE 'NEUTRAL' END
FROM (
    SELECT
        s.TICKET_ID, s.CUSTOMER_ID, s.CREATED_AT, s.CATEGORY, s.PRIORITY, s.STATUS, s.SUBJECT, s.DESCRIPTION,
        SNOWFLAKE.CORTEX.SENTIMENT(s.SUBJECT || '. ' || s.DESCRIPTION) AS SCORE
    FROM SILVER.SUPPORT_TICKET s
    WHERE s.TICKET_ID NOT IN (SELECT TICKET_ID FROM GOLD.SUPPORT_TICKET_ENRICHED)
) n;
